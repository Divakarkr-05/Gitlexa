import { FormEvent, useEffect, useRef, useState } from 'react';
import { ArrowLeft, ArrowUp, Bot, CircleHelp, Sparkles, X } from 'lucide-react';

interface AssistantExperienceProps {
  onClose: () => void;
}

interface Message {
  id: number;
  role: 'assistant' | 'user';
  text: string;
}

const suggestions = [
  'Why is our project blocked?',
  'Summarize failed builds.',
  'What needs attention in our pull requests?',
  'Explain the latest repository activity.',
];

const demoResponses = [
  {
    matches: ['blocked', 'blocker'],
    text: 'In this demo workspace, the release workflow is the top blocker: two sample test runs failed. PR #128 is also waiting for one reviewer. These are illustrative signals, not live repository findings.',
  },
  {
    matches: ['build', 'workflow', 'ci', 'failed'],
    text: 'The sample workflow pulse shows 2 failed runs out of 14 recent runs. The release test job is marked as the main item to inspect. This is simulated demo data; no CI provider is connected.',
  },
  {
    matches: ['pull', 'pr', 'review'],
    text: 'There are 4 sample open pull requests in this workspace. PR #128 is shown as waiting for one required review. These counts and review states are illustrative, not fetched from GitHub.',
  },
  {
    matches: ['activity', 'latest', 'commit'],
    text: 'The demo activity stream shows a sample auth middleware pull request, a push to feature/cache-headers, and a comment on the worker retry issue. This activity is simulated and not connected to GitHub.',
  },
];

function getDemoResponse(prompt: string): string {
  const normalized = prompt.toLowerCase();
  const match = demoResponses.find((response) => response.matches.some((term) => normalized.includes(term)));
  return match?.text
    ?? 'I can help you explore the sample repository health, blockers, workflows, pull requests, and activity shown in this demo. The assistant is simulated and does not query a live repository.';
}

export default function AssistantExperience({ onClose }: AssistantExperienceProps) {
  const [messages, setMessages] = useState<Message[]>([
    {
      id: 0,
      role: 'assistant',
      text: 'I’m your Gitlexa demo assistant. Ask me about the sample blockers, workflow status, pull requests, or recent activity. My answers are simulated—not generated by a live Bedrock or Alexa service.',
    },
  ]);
  const [draft, setDraft] = useState('');
  const [processing, setProcessing] = useState(false);
  const messageId = useRef(1);
  const headingRef = useRef<HTMLHeadingElement>(null);
  const timerRef = useRef<ReturnType<typeof setTimeout> | null>(null);

  useEffect(() => {
    headingRef.current?.focus();
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === 'Escape') onClose();
    };
    window.addEventListener('keydown', onKeyDown);
    return () => {
      window.removeEventListener('keydown', onKeyDown);
      if (timerRef.current) clearTimeout(timerRef.current);
    };
  }, [onClose]);

  function submitPrompt(prompt: string) {
    const trimmed = prompt.trim();
    if (!trimmed || processing) return;

    setMessages((current) => [...current, { id: messageId.current++, role: 'user', text: trimmed }]);
    setDraft('');
    setProcessing(true);
    timerRef.current = setTimeout(() => {
      setMessages((current) => [...current, {
        id: messageId.current++,
        role: 'assistant',
        text: getDemoResponse(trimmed),
      }]);
      setProcessing(false);
      timerRef.current = null;
    }, 550);
  }

  function handleSubmit(event: FormEvent<HTMLFormElement>) {
    event.preventDefault();
    submitPrompt(draft);
  }

  return (
    <main className="assistant-experience">
      <div className="assistant-topline">
        <button className="assistant-back-button" type="button" onClick={onClose}>
          <ArrowLeft size={16} aria-hidden="true" /> <span>Back to workspace</span>
        </button>
        <span className="assistant-top-brand"><span className="assistant-brand-icon"><Sparkles size={15} aria-hidden="true" /></span> GITLEXA <span>/</span> ALEXA+</span>
        <span className="assistant-top-status"><i aria-hidden="true" /> DEMO MODE</span>
      </div>

      <div className="assistant-stage">
        <div className="assistant-stage-glow" aria-hidden="true" />
        <div className="assistant-intro">
          <div className="assistant-brand-lockup"><span className="assistant-lockup-spark"><Sparkles size={16} aria-hidden="true" /></span><span>GITLEXA <b>+</b></span></div>
          <h1 ref={headingRef} tabIndex={-1}>Your repository.<br /><span>In conversation.</span></h1>
          <p>Ask about the signals in your workspace.</p>
          <div className="assistant-simulation-pill"><span /> SIMULATED ASSISTANT <b>·</b> NO LIVE AI CONNECTION</div>
        </div>

        <div className="assistant-orb-wrap" aria-hidden="true">
          <div className={`assistant-orb ${processing ? 'is-processing' : ''}`}>
            <span className="orb-halo orb-halo-one" />
            <span className="orb-halo orb-halo-two" />
            <span className="orb-core"><span /><i /></span>
            <span className="orb-orbit"><i /><i /><i /></span>
            <span className="orb-wave orb-wave-one" />
            <span className="orb-wave orb-wave-two" />
          </div>
          <span className="orb-caption">GITLEXA ASSISTANT</span>
        </div>

        <section className="assistant-conversation" aria-label="Demo conversation">
          <div className="conversation-head">
            <span className="conversation-label">CONVERSATION <span>·</span> SAMPLE REPOSITORY</span>
            <span className={`assistant-status ${processing ? 'processing' : ''}`} role="status" aria-live="polite"><i /> {processing ? 'Thinking…' : 'Ready to help'}</span>
          </div>
          <div className="conversation-messages" aria-live="polite" aria-relevant="additions">
            {messages.map((message) => (
              <article className={`conversation-message ${message.role}`} key={message.id}>
                {message.role === 'assistant' && <span className="message-avatar"><Bot size={15} aria-hidden="true" /></span>}
                <div className="message-body">
                  <div className="message-meta">{message.role === 'assistant' ? 'GITLEXA ASSISTANT' : 'YOU'}{message.role === 'assistant' && <span className="simulated-label">SIMULATED</span>}</div>
                  <p>{message.text}</p>
                </div>
              </article>
            ))}
            {processing && (
              <div className="processing-row" role="status"><span className="typing-indicator"><i /><i /><i /></span><span>Preparing a simulated response…</span></div>
            )}
          </div>
          <div className="suggested-prompts">
            <span className="suggested-label">TRY ASKING</span>
            <div className="suggestion-list">
              {suggestions.map((suggestion) => (
                <button type="button" key={suggestion} disabled={processing} onClick={() => submitPrompt(suggestion)}>
                  {suggestion}<ArrowUp size={12} aria-hidden="true" />
                </button>
              ))}
            </div>
          </div>
          <form className="assistant-composer" onSubmit={handleSubmit}>
            <label className="sr-only" htmlFor="assistant-prompt">Ask the Gitlexa demo assistant</label>
            <input
              id="assistant-prompt"
              type="text"
              value={draft}
              onChange={(event) => setDraft(event.target.value)}
              placeholder="Ask about your repository…"
              disabled={processing}
              autoComplete="off"
            />
            <button type="submit" disabled={processing || !draft.trim()} aria-label="Send message"><ArrowUp size={17} /></button>
          </form>
          <p className="assistant-demo-footnote"><CircleHelp size={12} aria-hidden="true" /> Responses are deterministic examples; no repository or AI service is queried.</p>
        </section>
      </div>
      <button className="assistant-exit-icon" type="button" onClick={onClose} aria-label="Close assistant"><X size={16} /></button>
    </main>
  );
}
